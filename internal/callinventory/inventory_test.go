package callinventory_test

import (
	"maps"
	"os"
	"slices"
	"testing"
	"testing/fstest"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/kapetan-io/tiger/internal/callinventory"
)

func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()
	module := fstest.MapFS{"go.mod": {Data: []byte("module example.test/mod\n\ngo 1.22\n")}}
	for name, content := range files {
		module[name] = &fstest.MapFile{Data: []byte(content)}
	}
	dir := t.TempDir()
	require.NoError(t, os.CopyFS(dir, module))
	return dir
}

func soleCall(t *testing.T, calls map[string]callinventory.Call) callinventory.Call {
	t.Helper()
	require.Len(t, calls, 1)
	return calls[slices.Sorted(maps.Keys(calls))[0]]
}

// Free functions are judged by their own body; methods by whether their package imports syscall.
func TestLoadKeepsOutsideCalleesOnlyWhenTheyReachSyscall(t *testing.T) {
	dir := writeModule(t, map[string]string{"a.go": `package mod

import (
	"os"
	"strings"
)

func Work() {
	_, _ = os.ReadFile("x")
	_ = strings.ToUpper("x")
}
`})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	calls := inv.Functions["mod.Work"].Calls
	assert.Equal(t, "os.ReadFile", soleCall(t, calls).Callee)
}

// A site is a file and line, so a reader opens one place however many calls sit there.
func TestLoadSiteIsFileAndLineSoTwoCallsOnOneLineAreOneSite(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"a.go": `package mod

import "example.test/mod/dep"

func Work() {
	dep.Do(); dep.Do()
}
`,
		"dep/dep.go": "package dep\n\nfunc Do() {}\n",
	})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	calls := inv.Functions["mod.Work"].Calls
	assert.Equal(t, []callinventory.Site{{File: "a.go", Line: 6}}, soleCall(t, calls).Sites)
}

func TestLoadSamePackageCallIsFlaggedAndSameOwnerCallIsDropped(t *testing.T) {
	dir := writeModule(t, map[string]string{"a.go": `package mod

type Store struct{}

func (s *Store) Flush() { s.sync() }

func (s *Store) sync() {}

func Work(s *Store) { helper() }

func helper() {}
`})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	assert.Empty(t, inv.Functions["mod.Store.Flush"].Calls)
	assert.False(t, inv.Functions["mod.Store.Flush"].CallsOut)

	work := inv.Functions["mod.Work"]
	assert.False(t, work.CallsOut)
	assert.True(t, soleCall(t, work.Calls).SamePackage)
}

// SSA names a second init function init#1; both must file under the package init.
func TestLoadFilesSecondInitUnderTheInitializer(t *testing.T) {
	dir := writeModule(t, map[string]string{"a.go": `package mod

import "example.test/mod/dep"

func init() { dep.Do() }

func init() { dep.Do() }
`, "dep/dep.go": "package dep\n\nfunc Do() {}\n"})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	init := inv.Functions["mod.init"]
	assert.True(t, init.Initializer)
	assert.Len(t, soleCall(t, init.Calls).Sites, 2)
	assert.NotContains(t, inv.Functions, "mod.init#1")
}

func TestLoadSkipsGeneratedFilesAndNamesThem(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"a.go": "package mod\n\nfunc Work() {}\n",
		"gen.go": `// Code generated by hand. DO NOT EDIT.

package mod

import "example.test/mod/dep"

func Made() { dep.Do() }
`,
		"dep/dep.go": "package dep\n\nfunc Do() {}\n",
	})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	assert.Equal(t, []string{"gen.go"}, inv.Generated)
	assert.NotContains(t, inv.Functions, "mod.Made")
}

func TestLoadNamesPackagesThatDoNotLoad(t *testing.T) {
	dir := writeModule(t, map[string]string{
		"a.go":       "package mod\n\nfunc Work() {}\n",
		"bad/bad.go": "package bad\n\nfunc Broken() { undefined() }\n",
	})
	inv, err := callinventory.Load(dir)
	require.NoError(t, err)

	assert.Equal(t, []string{"bad"}, inv.NotCompared)
	assert.Equal(t, []string{"example.test/mod/bad"}, inv.Unloaded)
	assert.NotEmpty(t, inv.LoadError)
}
