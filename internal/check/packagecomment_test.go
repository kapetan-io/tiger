package check_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/kapetan-io/tiger/internal/command"
)

const (
	longFinding = "TS-L15: this package comment runs past one paragraph — tiger expects it to " +
		"say only why the package exists — keep the first paragraph and move the rest into a " +
		"test, or delete it"
	emptyFinding = "TS-L16: this file holds only comments and the package clause — tiger " +
		"expects every production file to carry code — move any package comment above the " +
		"package clause of a file with code, then delete this file"
	splitFinding = "TS-L15: this is one of several files with a package comment, which go " +
		"doc joins into one — tiger expects one paragraph in one file — keep the package " +
		"comment in one file and delete it from the others"
	licence = "// Copyright 2026 The Fixture Authors.\n\n"
	docOnly = "// Package p exists.\npackage p\n"
)

func beside(t *testing.T, file sourceFile) string {
	t.Helper()
	dir := commentsModule(t, sourceFile{name: "code.go", content: "package p\n\ntype T struct{}\n"})
	require.NoError(t, os.WriteFile(filepath.Join(dir, file.name), []byte(file.content), 0o644))
	return dir
}

func TestPackageCommentFlagsMoreThanOneParagraph(t *testing.T) {
	for _, test := range []struct {
		name   string
		source string
	}{
		{name: "SecondParagraph", source: "// Package p exists.\n//\n// It works like this.\n"},
		{name: "Heading", source: "// Package p exists.\n//\n// # Ranking\n//\n// Rank.\n"},
		{name: "List", source: "// Package p exists:\n//   - one\n//   - two\n"},
		{name: "CodeBlock", source: "// Package p exists.\n//\n//\tp.Run()\n"},
		{name: "AfterLicence", source: licence + "// Package p exists.\n//\n// More.\n"},
	} {
		t.Run(test.name, func(t *testing.T) {
			dir := commentsModule(t, sourceFile{
				name: "p.go", content: test.source + "package p\n\ntype T struct{}\n",
			})
			got := run(t, "check", "-C", dir, "./...")
			assert.Empty(t, got.stderr)
			assert.Equal(t, command.ExitFindings, got.code)
			lines := splitLines(got.stdout)
			require.Len(t, lines, 2)
			assert.Contains(t, lines[0], "p.go:")
			assert.Contains(t, lines[0], longFinding)
			assert.Equal(t, "tiger: 1 blocking", lines[1])
		})
	}
}

