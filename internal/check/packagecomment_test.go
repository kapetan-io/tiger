func TestCommentOnlyFileIsAFinding(t *testing.T) {
	for _, test := range []struct {
		name   string
		file   string
		source string
		want   string
	}{
		{name: "DocGo", file: "doc.go", source: docOnly, want: "doc.go:2:1: "},
		{name: "AnyName", file: "words.go", source: docOnly, want: "words.go:2:1: "},
		{
			name: "LicenceAndPackageComment", file: "doc.go",
			source: licence + "// Package p exists.\npackage p\n", want: "doc.go:4:1: ",
		},
		{
			name: "LicenceOnly", file: "doc.go",
			source: licence + "package p\n", want: "doc.go:3:1: ",
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			dir := beside(t, sourceFile{name: test.file, content: test.source})
			got := run(t, "check", "-C", dir, "./...")
			assert.Empty(t, got.stderr)
			assert.Equal(t, command.ExitFindings, got.code)
			lines := splitLines(got.stdout)
			require.Len(t, lines, 2)
			assert.Contains(t, lines[0], test.want+emptyFinding)
			assert.Equal(t, "tiger: 1 blocking", lines[1])
		})
	}
}

