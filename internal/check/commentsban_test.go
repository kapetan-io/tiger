func commentsModule(t *testing.T, file sourceFile) string {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"),
		[]byte("module fixture.example/ban\n\ngo 1.26\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(dir, file.name), []byte(file.content), 0o644))
	return dir
}

func TestCommentsBanFlagsProse(t *testing.T) {
	const (
		head = "package p\n\n"
		decl = "type T struct{}\n"
		top  = "p.go:3:1: TS-L14: "
	)
	for _, test := range []struct {
		name   string
		source string
		want   string
	}{
		{name: "LineComment", source: head + "// x\nfunc F() {}\n", want: top},
		{name: "GroupIsOneFinding", source: head + "// a\n// b\n// c\n" + decl, want: top},
		{name: "InsideBody", source: head + "func F() {\n\t// x\n}\n", want: "p.go:4:2: TS-L14: "},
		{name: "BlockComment", source: head + "/* x */\n" + decl, want: top},
		{name: "BareSlashes", source: head + "//\n" + decl, want: top},
		{name: "TrailingOnPackageLine", source: "package p // x\n", want: "p.go:1:11: TS-L14: "},
		{name: "EasyjsonDirective", source: head + "//easyjson:json\n" + decl, want: top},
		{name: "WhyDirective", source: head + "//why:x\n" + decl, want: top},
		{name: "LintIgnore", source: head + "//lint:ignore SA1000 x\n" + decl, want: top},
		{name: "SpacedNolint", source: head + "// nolint\n" + decl, want: top},
		{name: "TripleSlashNolint", source: head + "///nolint\n" + decl, want: top},
	} {
		t.Run(test.name, func(t *testing.T) {
			dir := commentsModule(t, sourceFile{name: "p.go", content: test.source})
			got := run(t, "check", "-C", dir, "./...")
			assert.Empty(t, got.stderr)
			assert.Equal(t, command.ExitFindings, got.code)
			lines := splitLines(got.stdout)
			require.Len(t, lines, 2)
			assert.Contains(t, lines[0], test.want)
			assert.Equal(t, "tiger: 1 blocking", lines[1])
		})
	}
}

func TestCommentsBanKeepsMeaningfulComments(t *testing.T) {
	const (
		head = "package p\n\n"
		decl = "type A struct{}\n"
	)
	for _, test := range []struct {
		name   string
		file   string
		source string
	}{
		{
			name:   "TestFile",
			file:   "p_test.go",
			source: "package p_test\n\n// x\nfunc helper() {}\n",
		},
		{
			name: "GeneratedFile",
			file: "p.go",
			source: "// Code generated by hand. DO NOT EDIT.\n\n" + head +
				"// x\nfunc F() {}\n",
		},
		{
			name:   "PackageComment",
			file:   "p.go",
			source: "// Package p is above the line.\npackage p\n",
		},
		{
			name: "GoDirectives",
			file: "p.go",
			source: head + "//go:generate x\n" + decl + "\n//export F\ntype B struct{}\n\n" +
				"//line a.go:10\n\n/*line a.go:10*/\n",
		},
		{
			name:   "NolintDirective",
			file:   "p.go",
			source: head + "//nolint:errcheck // reason\n" + decl + "\n//nolint\ntype B struct{}\n",
		},
		{
			name: "CgoPreamble",
			file: "p.go",
			source: head + "/*\n#include <stdlib.h>\nstatic int one(void) { return 1; }\n*/\n" +
				"import \"C\"\n\nfunc One() int { return int(C.one()) }\n",
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			dir := commentsModule(t, sourceFile{name: test.file, content: test.source})
			got := run(t, "check", "-C", dir, "./...")
			assert.Empty(t, got.stderr)
			assert.Equal(t, command.ExitClean, got.code)
			assert.Empty(t, got.stdout)
		})
	}
}

func TestCommentsBanLeavesTheShippedPatternsClean(t *testing.T) {
	got := run(t, "check", "-C", filepath.Join("..", ".."), "./patterns/...")
	assert.Equal(t, command.ExitClean, got.code)
	assert.Empty(t, got.stdout)
	assert.Empty(t, got.stderr)
}
