// TestTestPackageReportsFilesThisRunDoesNotLoad covers TS-T12's coverage
// contract.
//
// Goal: a test file in the package under test is reported even when the go
// tool leaves it out of this run, because a build constraint excludes it here
// or because it is generated, and a file that is loaded is reported once.
func TestTestPackageReportsFilesThisRunDoesNotLoad(t *testing.T) {
	dir := writeModuleFiles(t, map[string]string{
		"go.mod":          "module testpackage.example/app\n\ngo 1.26\n",
		"a/a.go":          "// Package a has tests of every kind.\npackage a\n",
		"a/plain_test.go": "package a\n",
		"a/win_test.go":   "//go:build windows\n\npackage a\n",
		"a/int_test.go":   "//go:build integration\n\npackage a\n",
		"a/gen_test.go":   "// Code generated by x. DO NOT EDIT.\n\npackage a\n",
		"a/ext_test.go":   "package a_test\n",
		"b/b.go":          "// Package b has only an external test.\npackage b\n",
		"b/b_test.go":     "package b_test\n",
	})

	const advice = "which gives it every unexported name — declare package a_test and test " +
		"through the exported API\n"
	got := checkModule(t, dir)
	assert.Equal(t, cli.ExitFindings, got.code)
	assert.Equal(t,
		"a/gen_test.go:3:9: TS-T12: this test file declares package a, "+advice+
			"a/int_test.go:3:9: TS-T12: this test file declares package a, "+advice+
			"a/plain_test.go:1:9: TS-T12: this test file declares package a, "+advice+
			"a/win_test.go:3:9: TS-T12: this test file declares package a, "+advice+
			"tiger: 4 blocking\n", got.stdout)
	assert.Empty(t, got.stderr)
}

// TestTestPackageStaysWithinThePatterns covers TS-T12's scope contract.
//
// Goal: a directory named foo_test is its own package, so checking it leaves
// the sibling directory foo alone, while checking foo still reports foo's own
// test files.
func TestTestPackageStaysWithinThePatterns(t *testing.T) {
	dir := writeModuleFiles(t, map[string]string{
		"go.mod":           "module testpackage.example/app\n\ngo 1.26\n",
		"foo/foo.go":       "// Package foo has an internal test.\npackage foo\n",
		"foo/in_test.go":   "//go:build integration\n\npackage foo\n",
		"foo_test/help.go": "// Package helpers is a sibling.\npackage helpers\n",
	})

	got := run(t, "check", "-C", dir, "./foo_test")
	assert.Equal(t, cli.ExitClean, got.code)
	assert.Empty(t, got.stdout)

	got = run(t, "check", "-C", dir, "./foo")
	assert.Equal(t, cli.ExitFindings, got.code)
	assert.Equal(t, "foo/in_test.go:3:9: TS-T12: this test file declares package foo, which "+
		"gives it every unexported name — declare package foo_test and test through the "+
		"exported API\ntiger: 1 blocking\n", got.stdout)
}
